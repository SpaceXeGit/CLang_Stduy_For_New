void OLED_ShowEmoji(EmojiType_t emoji)
{
    if(emoji >= EMOJI_COUNT) return;
    OLED_Clear();
    OLED_DrawBitmap(48, 0, 32, 32, emoji_data[emoji]);
    OLED_ShowString(48, 40, (char*)emoji_name[emoji], 16);
    OLED_Refresh();
}
void OLED_EmojiAutoPlay(void)
{
    EmojiType_t i;

    for(i = 0; i < EMOJI_COUNT; i++)
    {
        OLED_ShowEmoji(i);
        delay_ms(2000);
    }
}
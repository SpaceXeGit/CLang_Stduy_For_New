#include <stdio.h>

int main() {
    // ==================== 整数格式符 ====================

    int num = 42;

    // %d - 十进制整数 (最常用)
    printf("%%d (十进制): %d\n", num);  // 输出：42

    // %i - 十进制整数 (与%d 类似，但支持八进制输入)
    printf("%%i (十进制): %i\n", num);  // 输出：42

    // %u - 无符号十进制整数
    unsigned int unum = 100;
    printf("%%u (无符号): %u\n", unum);  // 输出：100

    // %o - 八进制整数 (不带前缀 0)
    printf("%%o (八进制): %o\n", num);  // 输出：52 (42 的八进制)

    // %x - 十六进制整数 (小写 a-f, 不带前缀 0x)
    printf("%%x (十六进制小写): %x\n", num);  // 输出：2a

    // %X - 十六进制整数 (大写 A-F)
    printf("%%X (十六进制大写): %X\n", num);  // 输出：2A

    // %#x - 带前缀 0x 的十六进制
    printf("%%#x (带前缀): %#x\n", num);  // 输出：0x2a

    printf("\n");

    // ==================== 浮点数格式符 ====================

    float pi_f = 3.14159f;
    double pi_d = 3.14159265358979;

    // %f - 浮点数 (默认 6 位小数)
    printf("%%f (float): %f\n", pi_f);  // 输出：3.141590

    // %lf - double 类型 (scanf 时用，printf 中%f 即可)
    printf("%%lf (double): %lf\n", pi_d);  // 输出：3.141593

    // %.2f - 保留 2 位小数
    printf("%%.2f (2 位小数): %.2f\n", pi_f);  // 输出：3.14

    // %e - 科学计数法 (小写 e)
    printf("%%e (科学计数): %e\n", pi_d);  // 输出：3.141593e+000

    // %E - 科学计数法 (大写 E)
    printf("%%E (科学计数大写): %E\n", pi_d);  // 输出：3.141593E+000

    // %g - 自动选择%f或%e (取较短的)
    printf("%%g (自动选择): %g\n", pi_d);  // 输出：3.14159

    printf("\n");

    // ==================== 字符和字符串格式符 ====================

    char ch = 'A';
    char str[] = "Hello";

    // %c - 单个字符
    printf("%%c (字符): %c\n", ch);  // 输出：A

    // %s - 字符串
    printf("%%s (字符串): %s\n", str);  // 输出：Hello

    // %.3s - 只显示前 3 个字符
    printf("%%.3s (前 3 个字符): %.3s\n", str);  // 输出：Hel

    printf("\n");

    // ==================== 指针格式符 ====================

    int *ptr = &num;

    // %p - 指针地址 (十六进制)
    printf("%%p (指针地址): %p\n", ptr);  // 输出：类似 000000C42B9FF8D0

    printf("\n");

    // ==================== 其他格式符 ====================

    // %% - 输出百分号本身
    printf("%%%% (百分号): 100%%\n");  // 输出：100%

    // %n - 不输出内容，记录已输出的字符数到变量
    int count;
    printf("测试%%%n", &count);  // 输出：测试%
    printf(" (已输出%d个字符)\n", count);

    printf("\n");

    // ==================== 宽度和精度控制 ====================

    // %5d - 最小宽度 5，右对齐
    printf("%%5d (宽度 5): |%5d|\n", 42);  // 输出：|   42|

    // %-5d - 最小宽度 5，左对齐
    printf("%%-5d (左对齐): |%-5d|\n", 42);  // 输出：|42   |

    // %05d - 不足 5 位用 0 填充
    printf("%%05d (补零): %05d\n", 42);  // 输出：00042

    // %10.2f - 总宽度 10, 2 位小数
    printf("%%10.2f:|%10.2f|\n", 3.14);  // 输出：|      3.14|

    return 0;
}
